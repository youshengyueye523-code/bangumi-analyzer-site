/** 按发布日期倒序（数组本身已倒序，这里只做一次防御性排序） */
export function sortedVersions() {
  return [...versions].sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));
}

export function findVersion(version) {
  return versions.find((entry) => entry.version === version) ?? null;
}

/** 汇总所有版本里的设计取舍 / 实验 / 回退，供档案页使用 */
export function collectDecisions() {
  return versions.flatMap((entry) =>
    (entry.decisions ?? []).map((decision) => ({
      ...decision,
      version: entry.version,
      date: entry.date,
      versionTitle: entry.title,
    })),
  );
}

export function collectDevlog() {
  return versions
    .flatMap((entry) =>
      (entry.devlog ?? []).map((note) => ({
        ...note,
        version: entry.version,
        versionTitle: entry.title,
      })),
    )
    .sort((a, b) => (a.date < b.date ? 1 : a.date > b.date ? -1 : 0));
}
